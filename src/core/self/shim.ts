/**
 * The `claude-setup` command shim written into ~/.local/bin (the folder the Claude Code and uv
 * installers already put on PATH). Same approach as VS Code's `code` launcher: run the app's own
 * executable as Node (ELECTRON_RUN_AS_NODE=1) with out/main/cli.js.
 */
import { posix, win32 } from 'node:path'
import type { CliLaunch } from './launch'

/** First comment line of every generated shim; used to recognise our own file. */
export const SHIM_MARKER = 'Claude Setup command-line launcher'

/** File to write for the `claude-setup` command. */
export interface ShimPlan {
  path: string
  content: string
  /** POSIX permission bits (ignored on Windows). */
  mode: number
}

/** Quote a value for POSIX sh (single quotes, embedded quotes escaped). */
export function shQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`
}

const WINDOWS_PREFIX_VARS = ['LOCALAPPDATA', 'APPDATA', 'USERPROFILE', 'ProgramFiles', 'ProgramFiles(x86)'] as const

/**
 * Windows batch files are read in the console's OEM code page, so non-ASCII characters (e.g. in
 * user names) break. Replace well-known folder prefixes with %VAR% references (expanded as Unicode
 * by cmd.exe) and escape literal percent signs.
 */
export function windowsBatchPath(path: string, env: Record<string, string | undefined>): string {
  let best: { name: string; value: string } | undefined
  for (const name of WINDOWS_PREFIX_VARS) {
    const value = env[name]?.replace(/[\\/]+$/, '')
    if (!value || value.length < 3) continue
    const lower = path.toLowerCase()
    const v = value.toLowerCase()
    if ((lower === v || lower.startsWith(v + '\\') || lower.startsWith(v + '/')) && (!best || value.length > best.value.length)) {
      best = { name, value }
    }
  }
  if (!best) return path.replace(/%/g, '%%')
  return `%${best.name}%` + path.slice(best.value.length).replace(/%/g, '%%')
}

function isAscii(text: string): boolean {
  return /^[\x20-\x7e\r\n\t]*$/.test(text)
}

function windowsShim(launch: CliLaunch, env: Record<string, string | undefined>): string {
  const exe = windowsBatchPath(launch.exe, env)
  const script = windowsBatchPath(launch.script, env)
  const run = `"${exe}" "${script}" %*`
  const lines = ['@echo off', `rem ${SHIM_MARKER} (generated by Claude Setup; safe to delete)`, 'setlocal']
  if (launch.electron) lines.push('set "ELECTRON_RUN_AS_NODE=1"')
  lines.push('set "NODE_OPTIONS="')
  if (isAscii(run)) {
    lines.push(run, 'exit /b %ERRORLEVEL%')
  } else {
    // Rare: a non-ASCII path outside the well-known folders. Switch cmd.exe to UTF-8 while it reads
    // the next line, then restore the previous code page.
    lines.push(
      'for /f "tokens=2 delims=:." %%a in (\'chcp\') do set "CS_OLD_CP=%%a"',
      'chcp 65001 >nul',
      run,
      'set "CS_EXIT=%ERRORLEVEL%"',
      'for /f "tokens=1" %%b in ("%CS_OLD_CP%") do chcp %%b >nul',
      'exit /b %CS_EXIT%'
    )
  }
  return lines.join('\r\n') + '\r\n'
}

function posixShim(launch: CliLaunch): string {
  const lines = ['#!/bin/sh', `# ${SHIM_MARKER} (generated by Claude Setup; safe to delete)`, 'unset NODE_OPTIONS']
  if (launch.electron) lines.push('ELECTRON_RUN_AS_NODE=1', 'export ELECTRON_RUN_AS_NODE')
  lines.push(`exec ${shQuote(launch.exe)} ${shQuote(launch.script)} "$@"`)
  return lines.join('\n') + '\n'
}

/** What to write for the `claude-setup` command on this OS. */
export function cliShimPlan(
  launch: CliLaunch,
  platform: NodeJS.Platform,
  binDir: string,
  env: Record<string, string | undefined> = process.env
): ShimPlan {
  if (platform === 'win32') {
    return { path: win32.join(binDir, 'claude-setup.cmd'), content: windowsShim(launch, env), mode: 0o755 }
  }
  return { path: posix.join(binDir, 'claude-setup'), content: posixShim(launch), mode: 0o755 }
}

function normalizeDir(dir: string, platform: NodeJS.Platform, env: Record<string, string | undefined>): string {
  let d = dir.trim().replace(/^"(.*)"$/, '$1')
  if (platform === 'win32') {
    d = d.replace(/%([^%]+)%/g, (whole, name: string) => {
      const key = Object.keys(env).find((k) => k.toLowerCase() === name.toLowerCase())
      return key ? (env[key] ?? whole) : whole
    })
    return d.replace(/\//g, '\\').replace(/\\+$/, '').toLowerCase()
  }
  return d.replace(/\/+$/, '')
}

/** Read PATH from an environment object (Windows keys are case-insensitive: Path vs PATH). */
export function pathFromEnv(env: Record<string, string | undefined>, platform: NodeJS.Platform): string {
  if (platform !== 'win32') return env.PATH ?? ''
  const key = Object.keys(env).find((k) => k.toUpperCase() === 'PATH')
  return key ? (env[key] ?? '') : ''
}

/** Whether `dir` is one of the entries of a PATH string. */
export function isDirOnPath(
  dir: string,
  pathValue: string,
  platform: NodeJS.Platform,
  env: Record<string, string | undefined> = process.env
): boolean {
  const target = normalizeDir(dir, platform, env)
  const sep = platform === 'win32' ? ';' : ':'
  return pathValue
    .split(sep)
    .filter((entry) => entry.trim())
    .some((entry) => normalizeDir(entry, platform, env) === target)
}

/** Step-by-step instructions for adding `dir` to PATH, in plain language. */
export function pathAdvice(dir: string, platform: NodeJS.Platform, shell: string | undefined): string {
  if (platform === 'win32') {
    return [
      `Add ${dir} to your PATH so Windows can find the command:`,
      '1. Open Start, search for "environment variables" and choose "Edit environment variables for your account".',
      `2. Select "Path", click Edit, then New, and paste: ${dir}`,
      '3. Click OK, then open a new terminal window.',
      'Or run this once in PowerShell:',
      `[Environment]::SetEnvironmentVariable('Path', [Environment]::GetEnvironmentVariable('Path','User') + ';${dir}', 'User')`
    ].join('\n')
  }
  const shellName = (shell ?? '').split('/').pop() ?? ''
  const rc = shellName === 'zsh' ? '~/.zshrc' : shellName === 'fish' ? '~/.config/fish/config.fish' : '~/.bashrc'
  const line = shellName === 'fish' ? 'fish_add_path $HOME/.local/bin' : 'export PATH="$HOME/.local/bin:$PATH"'
  const command = shellName === 'fish' ? line : `echo '${line}' >> ${rc}`
  return [`Add ${dir} to your PATH so your terminal can find the command. Run this once:`, command, 'Then open a new terminal window.'].join(
    '\n'
  )
}
